def get_role_title(mode: RoleMode | str) -> str:
    try:
        role = RoleMode(mode)
    except ValueError:
        return str(mode)
    return ROLE_TITLES[role]


def get_system_prompt(mode: RoleMode | str) -> str:
    try:
        role = RoleMode(mode)
    except ValueError:
        role = RoleMode.ASSISTANT
    return f"{ROLE_PROMPTS[role]}\n\n{FILE_DELIVERY_PROMPT}"
